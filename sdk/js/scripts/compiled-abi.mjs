#!/usr/bin/env node
/**
 * Regenerates the compiled-ABI snapshots that both SDK test suites check their
 * hand-written ABIs against:
 *
 *   sdk/js/test/compiled-abi.ts
 *   sdk/python/tests/compiled_abi.py
 *
 * Run it after changing a contract: `node sdk/js/scripts/compiled-abi.mjs`.
 * Needs `forge` on PATH and the Foundry submodules installed. Each fragment is
 * written in ethers' `minimal` format (types only, no parameter names), e.g.
 * `function streams(address,address) view returns (address,int96,uint256,uint256)`,
 * so a snapshot pins inputs, outputs, mutability and which event args are indexed.
 */
import { execFileSync } from 'node:child_process';
import console from 'node:console';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ethers } from 'ethers';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../../..');
const CONTRACTS = ['PassportRegistry', 'ContextVault', 'ContextVaultIPFS', 'PaymentStream'];

const snapshot = {};
for (const name of CONTRACTS) {
  const json = execFileSync(
    'forge',
    ['inspect', `contracts/${name}.sol:${name}`, 'abi', '--json'],
    { cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }
  );
  const iface = new ethers.Interface(JSON.parse(json));
  snapshot[name] = iface.fragments
    .filter((fragment) => fragment.type !== 'constructor')
    .map((fragment) => fragment.format('minimal'))
    .sort();
}

const header =
  'Fragments of the compiled contracts in ethers\' `minimal` format, generated by\n' +
  'sdk/js/scripts/compiled-abi.mjs from `forge inspect`. Do not edit by hand.';

const ts = [
  '/**',
  ...header.split('\n').map((line) => ` * ${line}`),
  ' */',
  'export const COMPILED_ABI: Readonly<Record<string, readonly string[]>> = {',
  ...Object.entries(snapshot).flatMap(([name, fragments]) => [
    `  ${name}: [`,
    ...fragments.map((fragment) => `    ${JSON.stringify(fragment)},`),
    '  ],',
  ]),
  '};',
  '',
].join('\n');

const py = [
  `"""${header.replace(/\n/g, '\n')}"""`,
  '',
  'COMPILED_ABI: dict[str, frozenset[str]] = {',
  ...Object.entries(snapshot).flatMap(([name, fragments]) => [
    `    "${name}": frozenset(`,
    '        {',
    ...fragments.map((fragment) => `            ${JSON.stringify(fragment)},`),
    '        }',
    '    ),',
  ]),
  '}',
  '',
].join('\n');

const tsPath = resolve(here, '../test/compiled-abi.ts');
const pyPath = resolve(repoRoot, 'sdk/python/tests/compiled_abi.py');
writeFileSync(tsPath, ts);
writeFileSync(pyPath, py);
console.log(`wrote ${tsPath}\nwrote ${pyPath}`);
